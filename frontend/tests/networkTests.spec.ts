import { expect, test } from '@playwright/test';
import { desktopCalls } from './desktopMock';
import { mockNetworkTests } from './networkTestsMock';

test('网站测试只由手动触发，结果不影响主页刷新或守护', async ({ page }, info) => {
  await mockNetworkTests(page);
  await page.goto('/');
  await expect.poll(() => desktopCalls(page)).toContain('ready');
  await page.getByRole('button', { name: '网络测试', exact: true }).click();
  await expect(page.getByRole('heading', { name: '网络测试', exact: true })).toBeVisible();
  await expect(page.locator('.website-test-card')).toHaveCount(4);
  const calls = () => page.evaluate(() => (window as any).networkTestsFixture.calls);
  expect(await calls()).toEqual([]);
  await page.getByRole('button', { name: '测试全部', exact: true }).click();
  await expect(page.getByRole('button', { name: '添加网站', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '主页', exact: true }).click();
  await expect(page.locator('.refresh-button .fui-Spinner')).toHaveCount(0);
  expect(await desktopCalls(page)).not.toContain('check');
  expect(await desktopCalls(page)).not.toContain('guard-on');
  await expect.poll(() => page.evaluate(() => (window as any).networkTestsFixture.snapshot().busy)).toBe(false);
  await page.getByRole('button', { name: '网络测试', exact: true }).click();
  const baidu = page.getByLabel('百度测试结果', { exact: true });
  await expect(baidu.getByText('28 ms', { exact: true })).toBeVisible();
  await expect(baidu.locator('time')).toHaveAttribute('datetime', '2026-10-14T04:00:00.000Z');
  await expect(page.getByText('TLS 握手失败，请检查证书或网络', { exact: true })).toBeVisible();
  await expect(page.getByText('连接超时', { exact: true })).toBeVisible();
  await expect(baidu.getByText('连接成功', { exact: true })).toBeVisible();
  await expect(baidu.locator('.website-test-reason')).toBeEmpty();
  await expect(page.getByText(/HTTP 200/)).toHaveCount(0);
  await page.mouse.move(0, 0);
  await page.screenshot({ path: info.outputPath('network-tests.png') });
  await page.getByRole('button', { name: '测试Google', exact: true }).click();
  const google = page.getByLabel('Google测试结果', { exact: true });
  await expect(google.locator('.website-test-result > strong')).toHaveText('—');
  await expect(google.locator('time')).toHaveText('最近测试 —');
  await expect(google.getByText('连接超时', { exact: true })).toHaveCount(0);
  await expect(baidu.getByText('28 ms', { exact: true })).toBeVisible();
  await expect.poll(calls).toEqual(['test', 'test']);
  await expect.poll(() => page.evaluate(() => (window as any).networkTestsFixture.snapshot().busy)).toBe(false);
  await page.getByRole('button', { name: '测试全部', exact: true }).click();
  await expect(page.locator('.website-test-result > strong')).toHaveText(['—', '—', '—', '—']);
});

test('新增网址的校验、重复错误和删除，以及窄窗口布局', async ({ page }) => {
  await page.setViewportSize({ width: 520, height: 580 });
  await mockNetworkTests(page);
  await page.goto('/');
  await expect.poll(() => desktopCalls(page)).toContain('ready');
  await page.getByRole('button', { name: '网络测试', exact: true }).click();
  await page.getByRole('button', { name: '添加网站', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '添加网站', exact: true });
  await dialog.getByRole('textbox', { name: '网站名称', exact: true }).fill('测试网站');
  await dialog.getByRole('textbox', { name: '网址', exact: true }).fill('invalid');
  await dialog.getByRole('button', { name: '添加', exact: true }).click();
  await expect(dialog.getByText(/请输入完整的/)).toBeVisible();
  await dialog.getByRole('textbox', { name: '网址', exact: true }).fill('https://www.baidu.com/');
  await dialog.getByRole('button', { name: '添加', exact: true }).click();
  await expect(dialog.getByText(/此网址已在列表中/)).toBeVisible();
  await dialog.getByRole('textbox', { name: '网址', exact: true }).fill('https://example.test/');
  await dialog.getByRole('button', { name: '添加', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.locator('.website-test-card')).toHaveCount(5);
  const cards = await page.locator('.website-test-card').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().x));
  expect(new Set(cards).size).toBe(1);
  expect(await page.getByRole('main').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.getByRole('button', { name: '删除测试网站', exact: true }).click();
  await expect(page.locator('.website-test-card')).toHaveCount(4);
});
